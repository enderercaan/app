import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const matrix=JSON.parse(readFileSync('release/legal-language-applicability-r8.json','utf8'));
const review=JSON.parse(readFileSync('release/legal-language-review-v19.json','utf8'));
const docs=JSON.parse(readFileSync('release/legal-document-locales-v1.json','utf8'));
assert.equal(matrix.schema_version,1);
assert.equal(matrix.as_of,'2026-09-29');
assert.equal(Object.keys(matrix.markets).length,27,'27 markets required');
assert.equal(matrix.policy.ui_locale_is_not_legal_country,true);
assert.equal(matrix.policy.ui_locale_is_not_document_locale,true);
assert.equal(matrix.policy.legal_country_does_not_change_on_travel,true);
assert.equal(matrix.policy.statutory_or_required_document_language_overrides_ui_language,true);
assert.equal(matrix.policy.subnational_language_rule_requires_exact_subnational_route,true);
assert.equal(matrix.policy.silent_cross_language_fallback_for_binding_documents,'BLOCK');
assert.equal(matrix.policy.source_localization_complete_for_all_configured_document_locales,true);
assert.equal(matrix.policy.sworn_or_certified_translation_status_claimed,false);
const runtime=new Set(docs.runtime_ui_locales);
const legalOnly=new Set(docs.legal_document_only_locales.map(x=>x.locale));
for(const [code,m] of Object.entries(matrix.markets)){
  const r=review.markets[code];assert.ok(r,`${code}: review missing`);
  assert.equal(m.name,r.name,`${code}: name drift`);
  assert.deepEqual(m.configured_document_locales,r.launch_document_locales,`${code}: configured locale drift`);
  assert.equal(m.source_localization_status,'complete_internal_qa',`${code}: source localization must be complete`);
  assert.ok(m.classification&&m.scope_dimension&&m.rule_summary,`${code}: classification incomplete`);
  assert.ok(Array.isArray(m.official_sources)&&m.official_sources.length>0,`${code}: official source missing`);
  assert.equal(m.no_silent_fallback,true,`${code}: silent fallback must be blocked`);
  for(const l of m.source_localization_locales)assert.ok(runtime.has(l)||legalOnly.has(l),`${code}: source locale ${l} has no runtime/legal-only pack`);
  for(const l of m.minimum_document_locales_for_current_product_configuration)assert.ok(runtime.has(l)||legalOnly.has(l),`${code}: required locale ${l} has no pack`);
}
assert.equal(matrix.markets.AE.classification,'mandatory_local_language_general_consumer_ecommerce');
assert.deepEqual(matrix.markets.BE.minimum_document_locales_for_current_product_configuration,['fr','nl','de']);
assert.equal(matrix.markets.CA.classification,'subnational_mandatory_french_quebec');
assert.deepEqual(matrix.markets.ES.minimum_document_locales_for_current_product_configuration,['es','ca','eu','gl']);
assert.equal(matrix.markets.FR.classification,'mandatory_local_language_goods_services_information');
assert.equal(matrix.markets.ID.classification,'mandatory_bahasa_indonesia_for_agreements_involving_indonesian_party');
assert.equal(matrix.markets.IN.scope_dimension,'platform_status_and_user_choice');
assert.equal(matrix.markets.IT.classification,'mandatory_italian_consumer_information');
assert.equal(matrix.markets.KR.classification,'mandatory_hangul_standard_terms_if_applicable');
assert.equal(matrix.markets.RU.classification,'mandatory_russian_consumer_information');
assert.equal(matrix.markets.TH.scope_dimension,'business_model_conditional');
assert.equal(matrix.markets.US.scope_dimension,'federal_scope_specific_plus_state');
