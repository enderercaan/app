assert.ok(matrix.markets.ID.official_sources.some(x=>x.includes('jdih.komdigi.go.id/produk_hukum/view/id/832')),'ID Article 46 official source must remain canonical');
assert.match(matrix.markets.TH.authority_notification.deadline,/72_hours/);
assert.ok(matrix.markets.TH.official_sources.some(x=>x.includes('gppc.pdpc.or.th/portfolio/operational-training-installation-course-1-content-4')),'TH PDPC breach route must remain canonical');
