import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const readJson=(p)=>JSON.parse(readFileSync(p,'utf8'));
const matrix=readJson('release/security-incident-obligations-v19.json');
const official=readJson('release/official-source-review-v19.json');
assert.equal(matrix.policy,'fail_closed');
assert.equal(matrix.reviewed_at,'2026-09-30');
const expected=Object.keys(official.markets??{}).sort();
const actual=Object.keys(matrix.markets??{}).sort();
assert.deepEqual(actual,expected,'incident matrix must cover every configured market exactly once');
assert.equal(actual.length,27,'configured launch-market incident matrix must remain 27/27');
assert.match(matrix.default_release_effect,/Source-level incident legal review PASS/);
assert.match(matrix.internal_response_targets?.evidence_preservation??'',/immediate/);
assert.match(matrix.internal_response_targets?.privacy_legal_escalation??'',/60_minutes/);
assert.match(matrix.internal_response_targets?.clock_rule??'',/awareness.*detection.*determination/);
for(const code of actual){
  const row=matrix.markets[code]; const canonical=official.markets[code];
  assert.equal(row.country_name,canonical.name,`${code}: name drift`);
  assert.equal(row.external_counsel_confirmation_required,false,`${code}: external counsel must not be a source/legal prerequisite`);
  assert.equal(row.release_effect,'SOURCE_LEGAL_REVIEW_COMPLETE__LIVE_OPERATIONAL_EVIDENCE_SEPARATE',`${code}: incident source release effect`);
  assert.ok(row.authority_or_route?.length>3,`${code}: authority route missing`);
  assert.ok(row.authority_notification?.deadline?.length>3,`${code}: authority deadline/routing missing`);
  assert.ok(row.data_subject_notification?.deadline?.length>3,`${code}: data-subject deadline/routing missing`);
  assert.ok(row.recordkeeping?.minimum?.length>3,`${code}: recordkeeping missing`);
  assert.ok(row.special_cyber_reporting?.length>3,`${code}: cyber-reporting note missing`);
  assert.ok(Array.isArray(row.official_sources)&&row.official_sources.length>0,`${code}: official source missing`);
  const allowed=new Set(canonical.official_sources??[]);
  for(const url of row.official_sources){
    assert.match(url,/^https:\/\//,`${code}: source must use HTTPS`);
    assert.ok(allowed.has(url),`${code}: incident source is outside canonical official-source registry: ${url}`);
  }
  const topic=canonical.topics?.cybersecurity_breach_notification;
  assert.ok(topic,`${code}: canonical cybersecurity topic missing`);
  assert.deepEqual(row.official_sources,topic.evidence_reference,`${code}: incident matrix must use canonical cybersecurity topic sources`);
  assert.equal(row.official_source_topic_status,topic.status,`${code}: topic status drift`);
}
