function catalog(locale){
 const src=fs.readFileSync(path.join(root,'src/i18n/locales',`${locale}.ts`),'utf8');
 const body=/const messages:\s*Messages\s*=\s*\{([\s\S]*?)\n\};/.exec(src)?.[1]??'';
 return Function(`"use strict"; return ({${body}});`)();
}
const data={};
for(const locale of locales){const c=catalog(locale);data[locale]={};for(const k of keys){if(typeof c[k]!=='string'||!c[k].trim())throw new Error(`${locale}: missing ${k}`);data[locale][k]=c[k];}}
const q=v=>JSON.stringify(v, null, 2);
const out=`// GENERATED by scripts/generate-push-copy.mjs. Do not edit by hand.\n`+
`export const PUSH_COPY_LOCALES = ${q(locales)} as const;\n`+
`export const PUSH_TRANSLATED_LOCALES = ${q(locales)} as const;\n`+
`export type PushCopyLocale = typeof PUSH_TRANSLATED_LOCALES[number];\n`+
`export const PUSH_COPY: Record<PushCopyLocale, Record<string,string>> = ${q(data)};\n`;
const target=path.join(root,'supabase/functions/_shared/pushCopy.generated.ts');
if(process.argv.includes('--check')){
  const current=fs.existsSync(target)?fs.readFileSync(target,'utf8'):'';
  if(current!==out){console.error('generate-push-copy: BLOCKED generated push copy is stale');process.exit(1);}
  console.log(`generate-push-copy: CHECK PASS ${locales.length}/19 locales, ${keys.length} strings each`);
}else{
  fs.writeFileSync(target,out);
  console.log(`generate-push-copy: ${locales.length}/19 locales, ${keys.length} strings each`);
}
