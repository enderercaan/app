import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
const b=JSON.parse(readFileSync('release/language-coverage-boundary-v19.json','utf8'));
const legal=JSON.parse(readFileSync('release/legal-document-locales-v1.json','utf8'));
const runtimeFiles=readdirSync('src/i18n/locales').filter(x=>x.endsWith('.ts')).map(x=>x.slice(0,-3)).sort();
const expectedRuntime=[...b.runtime_ui_locales].sort();
const expectedLegal=[...b.legal_document_locales].sort();
const legalFromManifest=[...legal.runtime_ui_locales,...legal.legal_document_only_locales.map(x=>x.locale)].sort();
assert.equal(b.as_of,'2026-09-29');
assert.equal(b.summary.runtime_ui_locale_count,19);
assert.equal(b.summary.legal_document_locale_count,22);
assert.equal(b.summary.worldwide_language_coverage_complete,false);
assert.equal(b.policy.configured_locales_are_not_all_world_languages,true);
assert.equal(b.policy.source_translation_internal_qa_is_not_external_counsel_or_certified_translation,true);
assert.deepEqual(runtimeFiles,expectedRuntime,'runtime locale files drift from explicit language boundary');
assert.deepEqual(legal.runtime_ui_locales.sort(),expectedRuntime,'legal-document locale manifest runtime set drift');
assert.deepEqual(legalFromManifest,expectedLegal,'legal-document locale set drift');
assert.deepEqual([...b.legal_document_only_locales].sort(),['ca','eu','gl']);
console.log('language-coverage-boundary-checks: 19 runtime + 22 legal-document locales explicit; configured coverage is source-complete but not represented as all world languages');
